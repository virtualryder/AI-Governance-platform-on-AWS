import { NagSuppressions } from 'cdk-nag';
import { Stack } from 'aws-cdk-lib';

/**
 * Justified cdk-nag suppressions for the AgentPlatform stack (CLAUDE.md rule 6: each carries its
 * reason). The SMS-role findings are fixed at the source (TOTP-only MFA), leaving two items that are
 * correct for this design.
 */
export function applyAgentPlatformNagSuppressions(stack: Stack, opts: { hasInterceptor: boolean }): void {
  const sid = stack.stackName;

  // Cognito pool fronts an M2M client-credentials app client; MFA is a user-flow control that does
  // not apply to machine callers. User-facing clients added by a use-case must require MFA.
  NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/Identity/Pool/Resource`, [
    {
      id: 'AwsSolutions-COG2',
      reason:
        'This pool issues tokens to an M2M (client-credentials) app client, which has no interactive ' +
        'sign-in and therefore no MFA. The PLUS feature plan (threat protection) is enabled; use-case ' +
        'stacks that add user-facing clients must require MFA on those clients.',
    },
  ]);

  // Gateway execution role: CMK + (future) target permissions attached via Role.addToPolicy generate
  // a scoped inline DefaultPolicy; it is not shared, so the managed-policy reusability rationale
  // does not apply.
  NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/Gateway/Role/DefaultPolicy/Resource`, [
    {
      id: 'HIPAA.Security-IAMNoInlinePolicy',
      reason: 'Inline policy generated by Role.addToPolicy; tightly scoped (CMK use) to this stack and not shared.',
    },
    {
      id: 'AwsSolutions-IAM5',
      reason:
        'bedrock-agentcore:AuthorizeAction is scoped to this platform\'s gateway-name prefix ' +
        '(gateway/<name>-gw-*) because the gateway ARN carries a service-generated suffix that is ' +
        'unknown before the gateway is created. It is limited to this account and region.',
    },
  ]);

  if (!opts.hasInterceptor) return;

  // Per-user governance interceptor: a DynamoDB ledger of transient usage counters + the REQUEST
  // interceptor Lambda (hot path, idempotent, reaches only DynamoDB).
  NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/Interceptor/Ledger/Resource`, [
    {
      id: 'HIPAA.Security-DynamoDBInBackupPlan',
      reason:
        'The ledger holds transient per-user rate-limit/usage counters that self-expire via TTL; it is ' +
        'rebuildable and needs no backup plan. Point-in-time recovery is enabled.',
    },
  ]);
  NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/Interceptor/Fn/Resource`, [
    { id: 'AwsSolutions-L1', reason: 'Interceptor pins a specific current Python runtime for reproducible builds.' },
    {
      id: 'HIPAA.Security-LambdaConcurrency',
      reason: 'Per-request interceptor; concurrency scales with gateway traffic and is governed at the account level.',
    },
    {
      id: 'HIPAA.Security-LambdaDLQ',
      reason: 'Gateway retries interceptor failures (handler is idempotent); a DLQ is not the retry mechanism.',
    },
    {
      id: 'HIPAA.Security-LambdaInsideVPC',
      reason:
        'Reaches only DynamoDB over the AWS network and reads JWT claims/tool metadata; the platform baseline ' +
        'provisions no VPC. VPC isolation + a DynamoDB endpoint is a documented hardening option for regulated ' +
        'deployments.',
    },
  ]);
  NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/Interceptor/Fn/ServiceRole/Resource`, [
    { id: 'AwsSolutions-IAM4', reason: 'AWSLambdaBasicExecutionRole attached by the CDK Lambda construct for logs.' },
  ]);
  NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/Interceptor/Fn/ServiceRole/DefaultPolicy/Resource`, [
    {
      id: 'AwsSolutions-IAM5',
      reason: 'grantReadWriteData scopes DynamoDB actions to the ledger table and its indexes (table/index/*).',
    },
    {
      id: 'HIPAA.Security-IAMNoInlinePolicy',
      reason: 'Inline policy generated by Table.grantReadWriteData; scoped to the ledger table and not shared.',
    },
  ]);
}
