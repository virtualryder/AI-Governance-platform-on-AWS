import { NagSuppressions } from 'cdk-nag';
import { Stack } from 'aws-cdk-lib';

/**
 * Justified cdk-nag suppressions for the AgentPlatform stack (CLAUDE.md rule 6: each carries its
 * reason). The SMS-role findings are fixed at the source (TOTP-only MFA), leaving two items that are
 * correct for this design.
 */
export function applyAgentPlatformNagSuppressions(stack: Stack): void {
  const sid = stack.stackName;

  // Cognito pool fronts an M2M client-credentials app client; MFA is a user-flow control that does
  // not apply to machine callers. User-facing clients added by a use-case must require MFA.
  NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/Identity/Pool/Resource`, [
    {
      id: 'AwsSolutions-COG2',
      reason:
        'This pool issues tokens to an M2M (client-credentials) app client, which has no interactive ' +
        'sign-in and therefore no MFA. The PLUS feature plan (threat protection) is enabled; use-case ' +
        'stacks that add user-facing clients must require MFA on those clients.',
    },
  ]);

  // Gateway execution role: CMK + (future) target permissions attached via Role.addToPolicy generate
  // a scoped inline DefaultPolicy; it is not shared, so the managed-policy reusability rationale
  // does not apply.
  NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/Gateway/Role/DefaultPolicy/Resource`, [
    {
      id: 'HIPAA.Security-IAMNoInlinePolicy',
      reason: 'Inline policy generated by Role.addToPolicy; tightly scoped (CMK use) to this stack and not shared.',
    },
  ]);
}
