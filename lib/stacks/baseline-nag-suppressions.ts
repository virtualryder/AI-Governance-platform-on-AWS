import { NagSuppressions } from 'cdk-nag';
import { Stack } from 'aws-cdk-lib';

/**
 * Justified cdk-nag suppressions for GovernanceBaseline (CLAUDE.md rule 6: every suppression carries
 * its reason). Grouped by cause: the CDK-synthesized AwsCustomResource provider (not customer-
 * controllable), the CloudTrail delivery bucket, and L2-generated scoped inline policies.
 */
export function applyBaselineNagSuppressions(stack: Stack): void {
  const sid = stack.stackName;

  // --- Provisioning Lambdas (invocation-logging custom resource + CDK Provider framework): one-shot
  // CloudFormation lifecycle handlers, not request-serving functions. HIPAA Lambda operational rules
  // don't apply; suppressed stack-wide. (IAM4/IAM5/inline are suppressed on the specific constructs.)
  NagSuppressions.addStackSuppressions(stack, [
    {
      id: 'HIPAA.Security-LambdaConcurrency',
      reason: 'One-shot CloudFormation provisioning Lambda; concurrency limits add no value.',
    },
    {
      id: 'HIPAA.Security-LambdaDLQ',
      reason: 'Provisioning Lambda; failures surface as CloudFormation stack events/rollbacks.',
    },
    {
      id: 'HIPAA.Security-LambdaInsideVPC',
      reason: 'Provisioning Lambda calls only public Bedrock/SSM control-plane APIs; processes no customer data.',
    },
  ]);

  // --- Evidence/log bucket (CloudTrail delivery target).
  NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/Evidence/Bucket/Resource`, [
    {
      id: 'AwsSolutions-S1',
      reason:
        'This bucket is the CloudTrail delivery target. S3 server access logging would require a secondary ' +
        'self-logging bucket, and enabling S3 data events on the trail destination risks a logging loop. ' +
        'Access is constrained by block-public-access, TLS-only, Object Lock (WORM), CMK encryption and a ' +
        'least-privilege bucket policy; centralized access logging is provided by the hub log-archive (step 5).',
    },
    {
      id: 'HIPAA.Security-S3BucketLoggingEnabled',
      reason:
        'Same as AwsSolutions-S1: server access logging for the CloudTrail delivery bucket is centralized in ' +
        'the hub log-archive (step 5) rather than a per-account self-logging bucket.',
    },
    {
      id: 'HIPAA.Security-S3BucketReplicationEnabled',
      reason:
        'Cross-region replication of evidence is centralized in the hub log-archive (step 5). The single- ' +
        'account baseline relies on S3 durability + versioning + Object Lock and does not replicate.',
    },
  ]);

  // --- L2-generated scoped inline policies and required API wildcards.
  NagSuppressions.addResourceSuppressionsByPath(
    stack,
    `${sid}/InvocationLogging/DeliveryRole/DefaultPolicy/Resource`,
    [
      {
        id: 'AwsSolutions-IAM5',
        reason:
          'The Bedrock delivery role writes only to log streams inside the single invocation log group; ' +
          'stream names are created at runtime, so the log-stream:* wildcard is required and scoped to that ' +
          'one group.',
      },
      {
        id: 'HIPAA.Security-IAMNoInlinePolicy',
        reason: 'Inline policy generated by Role.addToPolicy; tightly scoped to this stack and not shared.',
      },
    ],
  );

  // (The invocation-logging custom-resource Lambda + CDK Provider IAM suppressions are co-located on
  // those constructs in invocation-logging.ts, robust to the framework's internal path naming.)

  // Cross-account evidence replication role (Gate 3) — only present when the spoke replicates to a hub.
  if (stack.node.tryFindChild('Evidence')?.node.tryFindChild('ReplicationRole')) {
    NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/Evidence/ReplicationRole/DefaultPolicy/Resource`, [
      {
        id: 'AwsSolutions-IAM5',
        reason:
          'S3 replication inherently needs object-level wildcards: read all source object versions ' +
          '(source-bucket/*), ReplicateObject/Delete/Tags on the hub archive (dest-bucket/*), and ' +
          'decrypt/encrypt with the source and hub CMKs. Scoped to those two buckets + keys.',
      },
      {
        id: 'HIPAA.Security-IAMNoInlinePolicy',
        reason: 'Inline policy generated by Role.addToPolicy for the replication role; scoped to this stack.',
      },
    ]);
  }

  NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/Audit/Trail/LogsRole/DefaultPolicy/Resource`, [
    {
      id: 'HIPAA.Security-IAMNoInlinePolicy',
      reason: 'Inline policy generated by the CloudTrail L2 to let the trail write to CloudWatch Logs; scoped.',
    },
  ]);
}
