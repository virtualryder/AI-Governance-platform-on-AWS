import { NagSuppressions } from 'cdk-nag';
import { Stack } from 'aws-cdk-lib';

/**
 * Justified cdk-nag suppressions for the Controls stack (CLAUDE.md rule 6: each carries its reason).
 * The kill-switch and HITL-approval functions are small control-plane Lambdas that touch only AWS
 * control-plane APIs and no customer data.
 */
export function applyControlsNagSuppressions(stack: Stack, opts: { hasHitl: boolean; hasDetective?: boolean }): void {
  const sid = stack.stackName;

  if (opts.hasDetective) {
    NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/Detective/Fn/ServiceRole/DefaultPolicy/Resource`, [
      {
        id: 'AwsSolutions-IAM5',
        reason:
          'The detective Config-rule Lambda needs account-wide reads (bedrock:GetModelInvocationLoggingConfiguration, ' +
          'bedrock:ListGuardrails) and config:PutEvaluations, none of which support resource-level scoping.',
      },
    ]);
  }

  NagSuppressions.addStackSuppressions(stack, [
    {
      id: 'AwsSolutions-L1',
      reason:
        'Control Lambdas pin a specific current Python runtime (3.13) for reproducible builds rather ' +
        'than floating to the newest runtime nag knows about.',
    },
    {
      id: 'HIPAA.Security-LambdaConcurrency',
      reason: 'Low-frequency control-plane Lambda (kill switch / approval callback); concurrency limits add no value.',
    },
    {
      id: 'HIPAA.Security-LambdaDLQ',
      reason: 'Invoked manually or by control events; failures surface directly to the operator, not via a DLQ.',
    },
    {
      id: 'HIPAA.Security-LambdaInsideVPC',
      reason:
        'Calls only AWS control-plane APIs (bedrock-agentcore, SSM, Step Functions); processes no customer ' +
        'data and has no VPC resources to reach.',
    },
    {
      id: 'AwsSolutions-IAM4',
      reason: 'AWSLambdaBasicExecutionRole is attached by the CDK Lambda construct for CloudWatch Logs only.',
    },
    {
      id: 'HIPAA.Security-IAMNoInlinePolicy',
      reason:
        'Inline policies are generated by CDK L2 constructs (Function.addToRolePolicy, grantTaskResponse); ' +
        'tightly scoped to this stack and not shared.',
    },
  ]);

  NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/KillSwitch/Fn/ServiceRole/DefaultPolicy/Resource`, [
    {
      id: 'AwsSolutions-IAM5',
      reason:
        'The kill switch manages Cedar policies on the account policy engine; Create/Delete/ListPolicies take ' +
        'no resource-level ARN. SSM access is scoped to the platform parameter prefix (/governed-ai/<c>/<e>/*).',
    },
  ]);

  if (opts.hasHitl) {
    NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/Hitl/Approval/Role/DefaultPolicy/Resource`, [
      {
        id: 'AwsSolutions-IAM5',
        reason:
          'grantTaskResponse grants states:SendTaskSuccess / SendTaskFailure, which do not support resource-level ' +
          'scoping to a single state machine.',
      },
    ]);
  }
}
