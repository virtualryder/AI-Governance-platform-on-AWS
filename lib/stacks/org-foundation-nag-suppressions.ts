import { NagSuppressions } from 'cdk-nag';
import { Stack } from 'aws-cdk-lib';

/** CDK-generated BucketDeployment provider + Guard-rules store findings (Guard Hooks). */
function applyGuardHookSuppressions(stack: Stack): void {
  const sid = stack.stackName;
  NagSuppressions.addStackSuppressions(stack, [
    { id: 'AwsSolutions-L1', reason: 'CDK BucketDeployment provider Lambda (one-shot Guard-rules upload) pins its own runtime.' },
    { id: 'HIPAA.Security-LambdaConcurrency', reason: 'CDK-managed BucketDeployment provider Lambda; one-shot rules upload, not customer-controllable.' },
    { id: 'HIPAA.Security-LambdaDLQ', reason: 'CDK-managed BucketDeployment provider Lambda; CloudFormation surfaces failures.' },
    { id: 'HIPAA.Security-LambdaInsideVPC', reason: 'CDK-managed BucketDeployment provider Lambda touches only S3; no VPC resources.' },
    { id: 'AwsSolutions-IAM4', reason: 'BucketDeployment provider role uses the AWS managed CloudWatch Logs policy.' },
    { id: 'AwsSolutions-IAM5', reason: 'Platform/CDK-generated roles whose actions have no resource-level scoping: the BucketDeployment provider (S3/KMS on the Guard-rules bucket) and the Budgets cost-action role (organizations:Attach/DetachPolicy — no resource ARN support). The break-glass deployer role IAM5 is additionally documented at its own resource path.' },
    { id: 'HIPAA.Security-IAMNoInlinePolicy', reason: 'Inline policies generated by CDK constructs (BucketDeployment provider, grantRead); scoped and not shared.' },
  ]);
  NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/GuardHooks/Rules/Resource`, [
    { id: 'AwsSolutions-S1', reason: 'Guard-rules store holds non-sensitive policy-as-code; access is constrained by block-public-access + TLS-only + versioning. Server access logging would need a secondary bucket.' },
    { id: 'HIPAA.Security-S3BucketLoggingEnabled', reason: 'Same as AwsSolutions-S1 — non-sensitive rules store; centralized logging via the hub log archive.' },
    { id: 'HIPAA.Security-S3BucketReplicationEnabled', reason: 'Rules are reproducible from source (policies/guard/); replication not warranted.' },
    { id: 'HIPAA.Security-S3DefaultEncryptionKMS', reason: 'S3-managed encryption is sufficient for non-sensitive, reproducible Guard rules; a CMK adds cost without protecting secrets.' },
  ]);
  NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/GuardHooks/ExecutionRole/DefaultPolicy/Resource`, [
    { id: 'AwsSolutions-IAM5', reason: 'grantRead scopes S3 read to the Guard-rules bucket and its objects (bucket + bucket/*).' },
    { id: 'HIPAA.Security-IAMNoInlinePolicy', reason: 'Inline policy generated by grantRead; scoped to the rules bucket and not shared.' },
  ]);
}

/**
 * Justified cdk-nag suppressions for OrgFoundation (CLAUDE.md rule 6). The deployer role is
 * deliberately the most privileged principal in the org — it is the single role every SCP exempts so
 * the platform can be deployed and repaired while all other principals are denied. Its breadth is the
 * design, not an oversight; it is scoped to the governance control plane and assumable only within
 * the account.
 */
export function applyOrgNagSuppressions(stack: Stack): void {
  const sid = stack.stackName;
  applyGuardHookSuppressions(stack);
  NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/OrgPolicies/DeployerRole/Resource`, [
    {
      id: 'HIPAA.Security-IAMNoInlinePolicy',
      reason: 'The SCP-exempt deployer role carries its governance-control-plane permissions inline; it is a single, named, non-shared break-glass role.',
    },
  ]);
  NagSuppressions.addResourceSuppressionsByPath(stack, `${sid}/OrgPolicies/DeployerRole/DefaultPolicy/Resource`, [
    {
      id: 'AwsSolutions-IAM5',
      reason:
        'The platform deployer is intentionally the privileged SCP-exempt role: it must retain full control ' +
        'of the governance services (bedrock, bedrock-agentcore, kms, s3, logs, iam, cloudformation, cloudtrail) ' +
        'that the SCPs lock everyone else out of, otherwise the platform cannot be deployed or repaired. ' +
        'Assumable only within the account (AccountRootPrincipal).',
    },
    {
      id: 'HIPAA.Security-IAMNoInlinePolicy',
      reason: 'Inline policy on the single named break-glass deployer role; not a shared/reusable policy.',
    },
    {
      id: 'HIPAA.Security-IAMPolicyNoStatementsWithFullAccess',
      reason:
        'Full-access on the governance services is intentional for the SCP-exempt deployer: it is the only ' +
        'principal permitted to administer the control plane the SCPs protect, so it can deploy/repair the ' +
        'platform. Breadth is the design of a break-glass role assumable only within the account.',
    },
  ]);
}
